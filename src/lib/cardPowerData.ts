export interface CardPowerRequirement {
  /** Power count (0 for free/no rune required, 1, 2, 3, etc.) */
  power: number;
  /** Whether the card is dual-domain mixed (playable with EITHER domain) */
  isMixed: boolean;
  /** Domain keys (e.g. ['fury'] or ['fury', 'chaos']) */
  domains: string[];
}

/**
 * Returns the exact Power Cost requirement for a card.
 */
export function getCardPowerRequirement(card?: {
  id?: string | null;
  card_number?: string | null;
  name?: string | null;
  domain?: string | null;
  card_type?: string | null;
} | null): CardPowerRequirement {
  if (!card) return { power: 0, isMixed: false, domains: [] };

  const cardType = (card.card_type || '').toLowerCase();
  if (['battlefield', 'legend', 'rune'].includes(cardType)) {
    return { power: 0, isMixed: false, domains: [] };
  }

  const rawDomains = (card.domain || '')
    .split(/[,/&]+/)
    .map(s => s.trim().toLowerCase())
    .filter(d => d && d !== 'colorless');

  if (rawDomains.length === 0) {
    return { power: 0, isMixed: false, domains: [] };
  }

  const isMixed = rawDomains.length > 1;

  // Check exact power map
  const code = (card.card_number || '').toUpperCase().trim();
  const shortCode = code.split('/')[0].trim();
  const normName = (card.name || '').toLowerCase().replace(/['"“”]/g, '').trim();
  const baseName = (card.name || '').toLowerCase().replace(/\(.*?\)/g, '').replace(/[-–—,]/g, ' ').replace(/\s+/g, ' ').trim();
  const idKey = (card.id || '').toLowerCase().trim();

  const power = CARD_POWER_MAP[code] ?? CARD_POWER_MAP[shortCode] ?? CARD_POWER_MAP[idKey] ?? CARD_POWER_MAP[normName] ?? CARD_POWER_MAP[baseName] ?? 0;

  return {
    power,
    isMixed,
    domains: rawDomains,
  };
}
